/**
 * Contact Inquiry Utilities & Order Identification
 * Distinguishes true customer contact/partner inquiries from product checkout/order entries.
 */

export const isOrderInquiry = (item: any): boolean => {
	if (!item) return false

	const details = item?.details || {}

	// 1. Explicit order identifiers in details payload
	if (
		details.order_id ||
		details.receipt_id ||
		details.order_type ||
		details.payment_mode ||
		details.payment_method ||
		details.payment_status ||
		details.product_name ||
		details.flavour ||
		details.razorpay_payment_id ||
		details.razorpay_order_id ||
		details.shipping_address
	) {
		return true
	}

	const rawSubject = (item?.subject || '').toString().trim()
	const subLower = rawSubject.toLowerCase()

	// 2. Order subject headings (ignoring customer inquiry topics such as "Order & Tracking Status")
	const isOrderSubject =
		/^\[?(?:product|paid|direct)?\s*order\]?/i.test(rawSubject) ||
		/^(?:ignite|product|paid|cod)\s*order\b/i.test(rawSubject) ||
		/\[(?:product|paid|direct)?\s*order\]/i.test(rawSubject) ||
		/\border\s*\[[a-z0-9_-]+\]/i.test(rawSubject) ||
		/\b(?:paid|product|direct)\s+order\b/i.test(rawSubject)

	if (isOrderSubject && !subLower.includes('contact inquiry') && !subLower.includes('inquiry -')) {
		return true
	}

	// 3. Message patterns generated by automated order checkout / landing pages
	const rawMessage = (item?.message || '').toString().trim().toLowerCase()
	if (
		rawMessage.startsWith('product order placed:') ||
		rawMessage.startsWith('=== ignite prepaid order') ||
		rawMessage.startsWith('=== ignite direct order') ||
		rawMessage.startsWith('=== ignite order') ||
		rawMessage.startsWith('test order manifest') ||
		/order placed:\s*[a-z0-9_-]+/i.test(rawMessage)
	) {
		return true
	}

	// 4. Source URL patterns indicating order completion or checkout
	const source = (item?.source || item?.Source || '').toString().trim().toLowerCase()
	if (
		source.includes('/order-confirmation') ||
		source.includes('/order-success') ||
		(source.includes('/thank-you') && (source.includes('order') || subLower.includes('order'))) ||
		(source.includes('/checkout') && !subLower.includes('inquiry'))
	) {
		return true
	}

	return false
}

export const isProPartnerApplication = (item: any): boolean => {
	if (!item || isOrderInquiry(item)) return false
	const subject = (item.subject || '').toString().toLowerCase()
	const details = item.details || {}
	return (
		subject.includes('partner') ||
		details.inquiryType === 'partner' ||
		Boolean(
			details.higher_education ||
			details.experience_years ||
			details.employment_type ||
			details.sales_potential ||
			details.certification_url
		)
	)
}

